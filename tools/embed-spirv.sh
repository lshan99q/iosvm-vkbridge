#
# Compiles shaders/oracle.comp and embeds the SPIR-V words into
# include/vkbridge/oracle_spirv.hpp so the build and the probe need no shader
# compiler. Run from the repository root:
#
#   tools/embed-spirv.sh
#
# Requires glslang-tools (glslangValidator); see README prerequisites.

set -eu

source_file=${1:-shaders/oracle.comp}
header_file=${2:-include/vkbridge/oracle_spirv.hpp}
spirv_file=$(mktemp)
trap 'rm -f "$spirv_file"' EXIT INT TERM

glslangValidator -V --target-env vulkan1.1 "$source_file" -o "$spirv_file" >/dev/null

if command -v spirv-val >/dev/null 2>&1; then
    spirv-val --target-env vulkan1.1 "$spirv_file"
fi

{
    echo '// SPDX-License-Identifier: MIT'
    echo '#pragma once'
    echo ''
    echo '#include <cstddef>'
    echo '#include <cstdint>'
    echo ''
    echo 'namespace vkbridge'
    echo '{'
    echo '// SPIR-V words for shaders/oracle.comp (the device-side attestation compute'
    echo '// shader). Generated by tools/embed-spirv.sh; do not edit by hand.'
    echo 'inline constexpr std::uint32_t kOracleSpirv[] = {'
    od -An -v -tu4 -w4 "$spirv_file" | awk '
        {
            printf "    0x%08Xu,", $1
            n += 1
            if (n % 8 == 0) {
                printf "\n"
            } else {
                printf " "
            }
        }
        END {
            if (n % 8 != 0) {
                printf "\n"
            }
        }'
    echo '};'
    echo ''
    echo 'inline constexpr std::size_t kOracleSpirvWordCount ='
    echo '    sizeof(kOracleSpirv) / sizeof(kOracleSpirv[0]);'
    echo ''
    echo '} // namespace vkbridge'
} >"$header_file"

if command -v clang-format >/dev/null 2>&1; then
    clang-format -i "$header_file"
fi

echo "wrote $header_file"
